def sha(p):
    h = hashlib.sha256()
    with p.open("rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def bind(rel):
    p = ROOT / rel
    if not p.is_file() or not p.stat().st_size:
        raise SystemExit("missing evidence: " + rel)
    return {"path": rel, "sha256": sha(p)}


