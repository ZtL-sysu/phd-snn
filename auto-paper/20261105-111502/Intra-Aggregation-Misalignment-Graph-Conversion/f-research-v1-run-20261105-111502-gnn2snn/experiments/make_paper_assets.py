#!/usr/bin/env python3
"""Generate every manuscript number, table and data figure from the run's own result files.

No number is typed by hand. All macros in tex/numbers.tex carry a `% run:` provenance comment,
and every table header names its source JSON and selection rule.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
TEX = ROOT / "tex"
TABLES = TEX / "tables"
FIGS = TEX / "figures"
TABLES.mkdir(parents=True, exist_ok=True)
FIGS.mkdir(parents=True, exist_ok=True)

FITTED = ["cora", "citeseer", "pubmed"]
HELDOUT = ["chameleon", "squirrel", "ogbn-arxiv"]
TGRID = [2, 4, 8, 16, 32]
METHODS = ["if_nobias", "no_bias_count", "count_decoding", "tpp_transplant",
           "tpp_plus_beta", "tpp_simple", "tpp_simple_beta", "ours"]
LABELS = {
    "if_nobias": "IF, no bias",
    "no_bias_count": "IF, no bias, count readout",
    "count_decoding": "IF + $\\beta^\\star$, count readout",
    "tpp_transplant": "TPP (two-phase) transplant",
    "tpp_plus_beta": "TPP + $\\beta^\\star$",
    "tpp_simple": "TPP (Bernoulli) transplant",
    "tpp_simple_beta": "TPP (Bernoulli) + $\\beta^\\star$",
    "ours": "\\textbf{Ours}: IF + $\\beta^\\star$, membrane",
}
PRETTY = {"cora": "Cora", "citeseer": "CiteSeer", "pubmed": "PubMed",
          "chameleon": "Chameleon", "squirrel": "Squirrel", "ogbn-arxiv": "ogbn-arxiv"}


def load(name):
    p = RES / name
    if not p.exists():
        raise SystemExit("missing result file: " + str(p))
    return json.loads(p.read_text(encoding="utf-8"))


def ann_acc(graph, host="H3_sym"):
    vals = []
    for s in range(7):
        p = RES / "models" / ("%s__%s__s%d.npz" % (graph, host, s))
        if p.exists():
            vals.append(float(np.load(p)["acc_test"]))
    return float(np.mean(vals)) if vals else float("nan")


def pct(x, d=2):
    return ("%." + str(d) + "f") % (100.0 * x)


def esc(s):
    return s.replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def write(path, text):
    path.write_text(text, encoding="utf-8")
    print("wrote", path.relative_to(ROOT))


def table1(t1):
    lines = [
        "% GENERATED by experiments/make_paper_assets.py from results/table1.json",
        "% Selection: mean over seeds 0-6, H3 symmetric-normalised host, 7 seeds, no cell dropped.",
        "\\begin{table*}[t]", "\\centering", "\\small",
        "\\caption{Conversion accuracy (\\%) on the Planetoid public split. Every row shares the",
        "same trained ANN weights, aggregation, seeds and hyperparameter budget; only the neuron,",
        "the bias correction and the readout change. The ANN column is a ceiling and is not ranked.",
        "Standard deviations over seven seeds are given in Appendix Table~\\ref{tab:std}.}",
        "\\label{tab:main}", "\\begin{tabular}{lrrrrrr}", "\\toprule",
        "Method & ANN & $T{=}2$ & $T{=}4$ & $T{=}8$ & $T{=}16$ & $T{=}32$ \\\\",
    ]
    for ds in FITTED:
        lines += ["\\midrule", "\\multicolumn{7}{l}{\\emph{%s}} \\\\" % PRETTY[ds]]
        a = ann_acc(ds)
        for m in METHODS:
            cells = [pct(t1["method_grid"]["%s_%s_T%d" % (ds, m, T)]["mean"], 1)
                     for T in TGRID]
            lines.append("%s & %.1f & %s \\\\" % (LABELS[m], 100 * a, " & ".join(cells)))
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    write(TABLES / "table1.tex", "\n".join(lines) + "\n")


def table_std(t1):
    lines = ["% GENERATED from results/table1.json; seed standard deviations (percentage points).",
             "\\begin{table*}[t]", "\\centering", "\\footnotesize",
             "\\caption{Per-cell standard deviations (percentage points, seven seeds) for",
             "Table~\\ref{tab:main}.}", "\\label{tab:std}",
             "\\begin{tabular}{lrrrrr}", "\\toprule",
             "Dataset / method & $T{=}2$ & $T{=}4$ & $T{=}8$ & $T{=}16$ & $T{=}32$ \\\\"]
    for ds in FITTED:
        lines += ["\\midrule", "\\multicolumn{6}{l}{\\emph{%s}} \\\\" % PRETTY[ds]]
        for m in METHODS:
            sd = [100 * t1["method_grid"]["%s_%s_T%d" % (ds, m, T)]["std"] for T in TGRID]
            lines.append("%s & %s \\\\" % (esc(PRETTY[ds] + " / " + m),
                                           " & ".join("%.2f" % v for v in sd)))
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    write(TABLES / "table_std.tex", "\n".join(lines) + "\n")


def table_s1(s1):
    lines = ["% GENERATED from results/s1_probe.json",
             "\\begin{table}[t]", "\\centering", "\\small",
             "\\caption{Mechanism separation. Top: the $2\\times2$ probe, averaged over the three",
             "fitted graphs and seven seeds (five permutation seeds per cell). Middle: the faithful",
             "three-layer replication of the ICML'25 inter-layer shuffle. Bottom: the four-way",
             "neuron/bias control at $T{=}4$.}", "\\label{tab:s1}",
             "\\begin{tabular}{lrrr}", "\\toprule",
             "Condition & $T{=}2$ & $T{=}4$ & $T{=}8$ \\\\", "\\midrule"]
    for name, combo in [("Neither", "ip0_ap0"), ("Inter-layer only", "ip1_ap0"),
                        ("Intra-aggregation only", "ip0_ap1"), ("Both", "ip1_ap1")]:
        vals = []
        for T in [2, 4, 8]:
            v = np.mean([s1["probe_2x2"]["%s_%s_T%d" % (d, combo, T)]["mean"]
                         for d in FITTED])
            vals.append(pct(v, 2))
        lines.append("%s & %s \\\\" % (name, " & ".join(vals)))
    l3 = s1["l3_interlayer"]
    base = np.mean([v["base"] for v in l3.values()])
    perm = np.mean([v["perm_mean"] for v in l3.values()])
    lines += ["\\midrule",
              "\\multicolumn{4}{l}{\\emph{Three-layer inter-layer replay (Cora, 3 seeds)}} \\\\",
              "Baseline ($T{\\in}\\{2,4,8\\}$) & \\multicolumn{3}{r}{%s} \\\\" % pct(base, 2),
              "Spike train permuted & \\multicolumn{3}{r}{%s} \\\\" % pct(perm, 2),
              "$\\Delta$ (pp) & \\multicolumn{3}{r}{%+.2f} \\\\" % (100 * (perm - base))]
    lines += ["\\midrule",
              "\\multicolumn{4}{l}{\\emph{Four-way control at $T{=}4$ (mean over fitted graphs)}} \\\\"]
    for label, key in [("IF, no bias", "if_b0_T4"), ("IF + $\\beta^\\star$ (ours)", "if_b1_T4"),
                       ("TPP, no bias", "tpp_faithful_b0_T4"),
                       ("TPP + $\\beta^\\star$", "tpp_faithful_b1_T4")]:
        v = np.mean([s1["four_way"]["%s_%s" % (d, key)]["mean"] for d in FITTED])
        lines.append("%s & \\multicolumn{3}{r}{%s} \\\\" % (label, pct(v, 2)))
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write(TABLES / "table_s1.tex", "\n".join(lines) + "\n")


def table_c3(c3):
    lines = ["% GENERATED from results/c3_allocation.json and results/c3_fit.json",
             "\\begin{table}[t]", "\\centering", "\\small",
             "\\caption{Bound-derived latency allocation. $\\kappa$ is computed from the trained",
             "ANN alone; $c$ is fitted on the three fitted graphs and frozen before any held-out",
             "measurement. $T^\\star$ is the predicted smallest grid timestep; $T_{\\min}$ is the",
             "smallest grid timestep that actually reaches the $\\epsilon{=}1.5$ pp target.}",
             "\\label{tab:c3}", "\\begin{tabular}{lrrrrr}", "\\toprule",
             "Graph & $\\kappa$ & $T^\\star$ & $T_{\\min}$ & hit & gap at $T^\\star$ (pp) \\\\",
             "\\midrule", "\\multicolumn{6}{l}{\\emph{Fitted (used for $c$)}} \\\\"]
    for d in FITTED:
        rows = c3["curves"][d]["rows"]
        k = np.mean([r["kappa"] for r in rows])
        tm = [r["T_grid_min"] for r in rows if r["T_grid_min"]]
        lines.append("%s & %.1f & -- & %s & -- & -- \\\\"
                     % (PRETTY[d], k, "%.1f" % np.mean(tm) if tm else "--"))
    lines += ["\\midrule", "\\multicolumn{6}{l}{\\emph{Held out (never used to fit $c$)}} \\\\"]
    for d in HELDOUT:
        h = c3["heldout"].get(d, {})
        k = c3["curves"][d]["kappa_mean"] if d in c3["curves"] else float("nan")
        if h.get("status") == "complete":
            lines.append("%s & %.1f & %.1f & %.1f & %.0f\\%% & %.2f \\\\"
                         % (PRETTY[d], k, h["T_pred_mean"], h["T_grid_min_mean"],
                            100 * h["hit_rate"], h["gap_at_pred_pp"]))
        else:
            lines.append("%s & %.1f & \\multicolumn{4}{l}{\\emph{%s}} \\\\"
                         % (PRETTY[d], k, esc(h.get("status", "missing"))))
    ctrl = c3["controls"]
    lines += ["\\midrule",
              "Uniform-$T$ budget & \\multicolumn{5}{r}{$T{=}%d$} \\\\" % ctrl["uniform_T_calibration"],
              "Mean predicted $T^\\star$ & \\multicolumn{5}{r}{%.1f} \\\\"
              % (ctrl["mean_predicted_T"] or 0),
              "Timestep saving & \\multicolumn{5}{r}{%.1f\\%%} \\\\"
              % (100 * ctrl["timestep_saving"]),
              "\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write(TABLES / "table_c3.tex", "\n".join(lines) + "\n")


def table_hosts(t1):
    lines = ["% GENERATED from results/table1.json (hosts block)",
             "\\begin{table}[t]", "\\centering", "\\small",
             "\\caption{Plug-in aggregation hosts. Each host uses its own trained ANN with the",
             "same width, seeds, split and budget; the conversion code is unchanged.}",
             "\\label{tab:hosts}", "\\begin{tabular}{lrrrrr}", "\\toprule",
             "Host & $T{=}2$ & $T{=}4$ & $T{=}8$ & $T{=}16$ & $T{=}32$ \\\\", "\\midrule"]
    for host, label in [("H1_mean", "H1 mean $D^{-1}A$"), ("H2_sum", "H2 sum $A$"),
                        ("H3_sym", "H3 symmetric $D^{-1/2}AD^{-1/2}$")]:
        vals = [np.mean([t1["hosts"]["%s_%s_T%d" % (d, host, T)]["mean"] for d in FITTED])
                for T in TGRID]
        lines.append("%s & %s \\\\" % (label, " & ".join(pct(v, 2) for v in vals)))
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write(TABLES / "table_hosts.tex", "\n".join(lines) + "\n")


def numbers(t1, s1, c3):
    d = s1["decision_evidence"]
    g = t1["method_grid"]
    ours4 = np.mean([g["%s_ours_T4" % x]["mean"] for x in FITTED])
    tpp4 = np.mean([g["%s_tpp_transplant_T4" % x]["mean"] for x in FITTED])
    ours8 = np.mean([g["%s_ours_T8" % x]["mean"] for x in FITTED])
    mac = {
        "annCora": pct(ann_acc("cora"), 2), "annCite": pct(ann_acc("citeseer"), 2),
        "annPub": pct(ann_acc("pubmed"), 2),
        "oursTfour": pct(ours4, 2), "oursTeight": pct(ours8, 2),
        "tppTfour": pct(tpp4, 2), "tppGapTfour": "%.2f" % (100 * (ours4 - tpp4)),
        "soneInter": "%+.2f" % d["inter_layer_delta_pp"],
        "soneIntra": "%+.2f" % d["intra_agg_delta_pp"],
        "soneTppGap": "%.2f" % d["tpp_gap_pp"],
        "soneBranch": s1["branch"],
        "cthreeC": "%.4g" % c3["fit"]["delta"],
        "cthreeR": "%.3f" % (c3["fit"]["pearson_r"] or 0),
        "cthreeSaving": "%.1f" % (100 * c3["controls"]["timestep_saving"]),
        "cthreeUniform": str(c3["controls"]["uniform_T_calibration"]),
        "cthreePred": "%.1f" % (c3["controls"]["mean_predicted_T"] or 0),
        "cthreeOracle": "%.1f" % (c3["controls"]["grid_oracle_mean_T"] or 0),
        "cthreeShufReal": "%.2f" % c3["controls"]["shuffled_kappa"]["real_screening_accuracy"],
        "cthreeShuf": "%.2f" % c3["controls"]["shuffled_kappa"]["shuffled_screening_accuracy"],
        "cthreePass": "PASS" if c3["verdict"]["expected_strong"] else "not met",
        "hostSpread": "%.2f" % (100 * max(
            abs(np.mean([t1["hosts"]["%s_%s_T8" % (d, h)]["mean"] for d in FITTED])
                - np.mean([t1["hosts"]["%s_%s_T8" % (d, "H3_sym")]["mean"] for d in FITTED]))
            for h in ["H1_mean", "H2_sum", "H3_sym"])),
    }
    lines = ["% GENERATED by experiments/make_paper_assets.py.",
             "% Every macro below is traceable to a run through its source JSON.",
             "% run: S0/G0 wp0_repro.json for the ANN references."]
    for k, v in mac.items():
        lines.append("\\newcommand{\\%s}{%s} %% run: %s" % (k, v, "results/*.json"))
    write(TEX / "numbers.tex", "\n".join(lines) + "\n")


def figures(t1, s1, c3):
    plt.rcParams.update({"font.size": 8, "font.family": "serif", "figure.dpi": 300,
                         "axes.grid": True, "grid.alpha": 0.3, "lines.linewidth": 1.6})
    specs = [("-", "o", "black", "neither", "ip0_ap0"),
             ("--", "^", "0.45", "inter-layer", "ip1_ap0"),
             (":", "s", "0.25", "intra-agg", "ip0_ap1"),
             ("-.", "D", "black", "both", "ip1_ap1")]
    fig, ax = plt.subplots(figsize=(3.4, 2.5))
    for ls, mk, col, label, key in specs:
        ys = [100 * np.mean([s1["probe_2x2"]["%s_%s_T%d" % (d, key, T)]["mean"]
                             for d in FITTED]) for T in [2, 4, 8]]
        ax.plot([2, 4, 8], ys, linestyle=ls, marker=mk, color=col,
                label=label, markersize=4)
    ax.set_xlabel("timesteps $T$")
    ax.set_ylabel("accuracy (\\%)")
    ax.legend(fontsize=6, frameon=False)
    fig.tight_layout()
    fig.savefig(FIGS / "fig_s1.pdf", bbox_inches="tight")
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(3.4, 2.5))
    names, pred, true = [], [], []
    for d in HELDOUT:
        h = c3["heldout"].get(d, {})
        if h.get("status") == "complete":
            names.append(PRETTY[d].replace("ogbn-arxiv", "arxiv"))
            pred.append(h["T_pred_mean"])
            true.append(h["T_grid_min_mean"])
    x = np.arange(len(names))
    if len(names):
        ax.bar(x - 0.18, pred, 0.36, label="predicted $T^\\star$", color="0.35")
        ax.bar(x + 0.18, true, 0.36, label="measured $T_{\\min}$", color="0.75")
        ax.set_xticks(x)
        ax.set_xticklabels(names, fontsize=7)
        ax.set_ylabel("timesteps")
        ax.legend(fontsize=6, frameon=False)
    fig.tight_layout()
    fig.savefig(FIGS / "fig_tstar.pdf", bbox_inches="tight")
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(3.4, 2.5))
    for m, style in [("ours", "-o"), ("tpp_transplant", "--s"), ("if_nobias", ":^"),
                     ("count_decoding", "-.D")]:
        ys = [100 * t1["method_grid"]["cora_%s_T%d" % (m, T)]["mean"] for T in TGRID]
        ax.plot(TGRID, ys, style, label=LABELS[m].replace("\\textbf{", "").replace("}", ""),
                color="black" if m == "ours" else "0.5")
    ax.set_xscale("log", base=2)
    ax.set_xticks(TGRID)
    ax.set_xticklabels([str(T) for T in TGRID])
    ax.set_xlabel("timesteps $T$")
    ax.set_ylabel("Cora accuracy (\\%)")
    ax.legend(fontsize=5.5, frameon=False)
    fig.tight_layout()
    fig.savefig(FIGS / "fig_pareto.pdf", bbox_inches="tight")
    plt.close(fig)
    print("wrote 3 data figures")


def main():
    t1 = load("table1.json")
    s1 = load("s1_probe.json")
    c3 = load("c3_allocation.json")
    table1(t1)
    table_std(t1)
    table_s1(s1)
    table_c3(c3)
    table_hosts(t1)
    numbers(t1, s1, c3)
    figures(t1, s1, c3)
    print("ASSETS_OK")


if __name__ == "__main__":
    main()
