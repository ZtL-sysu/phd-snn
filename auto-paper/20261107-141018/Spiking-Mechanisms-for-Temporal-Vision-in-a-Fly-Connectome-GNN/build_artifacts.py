FILES["theoretical-feasibility-audit.md"] = """
# Theoretical / algorithm feasibility audit

**Causal mechanism.** A stateless GNN applies `x_t = tanh(A x_{t-1}^{(input)})` independently to
each frame; the readout then averages frame-wise features, which is permutation-invariant in
time for the label. A direction label requires comparing position at t and t+k. LIF keeps a
membrane potential `v_t = decay*v_{t-1} + syn(spikes_{t-1}) + drive_t`, so the state at time t
carries a decaying trace of earlier frames — a sufficient statistic for direction at short T.
Measured locally: Kenyon feature std rises from 8.1e-05 (stateless) to 5.0e-03 (LIF+homeostasis).

**Assumptions.** (i) T is short relative to the decay window; (ii) synaptic current must cross
the firing threshold without diverging (fixed gain either fails to reach deep layers or causes
positive-feedback explosion — measured in rounds 1–3); (iii) the readout has enough
signal-to-noise after propagation; (iv) stimuli are labelled by temporal property, not shape.

**Falsifying ablations.** stateless (no state), A=0 (no propagation), flash task (no
cross-frame integration needed), one-factor removal from the stacked mechanism, sign shuffle,
degree-preserving null. If any of these erase the predicted pattern, the mechanism story fails.

**Failure mode for the tier.** If the gain persists only for synthetic dot stimuli, or if the
stacked mechanism adds no attributable gain, the result is a diagnostic note rather than a
CVPR main-conference paper. This is recorded as G8 pending, not waived.
"""

